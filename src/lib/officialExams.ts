/**
 * **평가원이 시행하는 정식 시험**(6월·9월 모의평가, 수능)의 응시일 표.
 *
 * 사설 실모와 정식 시험은 성적의 무게가 다르다 — 추세를 볼 때 기준이 되는
 * 것은 정식 시험이다(사용자 요청 — "9월 2일에 쳤다고 입력한 것들은 정식
 * 9모니까 좀 강조해놔 그래프에서"). 그래서 그 날짜의 점을 그래프에서 도드라지게
 * 그리고, 세로 안내선과 이름을 함께 얹는다.
 *
 * **날짜를 추측해서 채우지 않는다.** 시행일은 해마다 다르고, 이 저장소는
 * "정확한 근거 없이 떠도는 숫자를 믿지 않는다"를 여러 번 데면서 배웠다(모델
 * 이름·단가가 그랬다). 지금 들어 있는 것은 **사용자가 직접 알려 준 것뿐**이다.
 * 6월 모의평가나 수능을 넣으려면 그 시행일을 확인한 뒤 한 줄 더할 것 —
 * 없는 날짜는 그냥 표시가 안 될 뿐이라 잘못 넣는 쪽이 훨씬 나쁘다.
 *
 * 이 파일에는 네트워크 호출도 환경변수도 없다(화면에 그대로 실린다 —
 * `problemBoxes.ts`·`gradeSummary.ts`·`problemOrder.ts` 와 같은 이유).
 */
export const OFFICIAL_EXAMS: Readonly<Record<string, string>> = {
  // 아래 둘 다 사용자가 직접 알려 준 시행일이다(2026-09-06 확인).
  "2026-06-04": "6월 모의평가",
  "2026-09-02": "9월 모의평가",
};

/** 이 날짜에 시행된 정식 시험 이름. 없으면 undefined(사설 실모 등). */
export function officialExamOn(takenAt: string): string | undefined {
  return OFFICIAL_EXAMS[takenAt];
}
